import {test} from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import {existsSync} from 'node:fs';
import {readFile} from 'node:fs/promises';
import {createServer} from 'node:http';
test('standalone game, persistent records, admin publish/restore and isolated preview',async()=>{
 const html=await readFile('fab-reaction-timer.html');
 const server=createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end(html);});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const url='http://127.0.0.1:'+server.address().port+'/';
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined),args:['--no-sandbox']});
 try {
 const page=await browser.newPage();const errors=[];
 page.on('request',req=>assert.ok(req.url().startsWith(url),'Standalone must not load external resources')); page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url);
 await page.getByRole('heading',{name:'TEST YOUR REACTION TIME'}).waitFor();
 await page.evaluate(()=>document.fonts.ready);
 assert.equal(await page.evaluate(()=>document.fonts.check('16px "FS Matthew"')),true);
 assert.ok(await page.evaluate(()=>getComputedStyle(document.body).fontFamily.includes('FS Matthew')));
 await page.getByPlaceholder('ENTER FULL NAME').fill('Test Player');


 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'PRESS HERE TO BEGIN',exact:true}).click();
 await page.getByRole('button',{name:'PRESS HERE TO BEGIN',exact:true}).click();
 await page.getByRole('button',{name:'STOP TIMER'}).waitFor();
 await page.waitForTimeout(1100);await page.getByRole('button',{name:'STOP TIMER'}).click();
 await page.getByText('TRY AGAIN',{exact:true}).waitFor();
 let records=await page.evaluate(()=>JSON.parse(localStorage.getItem('fab-records')));
 assert.equal(records.length,1);assert.equal(records[0].target,10);assert.equal(records[0].qualified,false);assert.ok(records[0].finalTime>=1);
 await page.reload();await page.getByRole('button',{name:'VIEW LEADERBOARD'}).click();await page.getByText('TEST PLAYER',{exact:true}).waitFor();
 assert.equal(await page.getByRole('link',{name:'Admin studio'}).count(),0);
 await page.goto(url+'admin');
 await page.getByRole('button',{name:'Leaderboard',exact:true}).click();
 await page.getByRole('table',{name:'Admin leaderboard'}).getByText('TEST PLAYER',{exact:true}).waitFor();
 await page.getByLabel('Search players').fill('nobody');await page.getByText('No players match your search.').waitFor();
 await page.getByLabel('Search players').fill('Test Player');
 assert.equal(await page.getByRole('table',{name:'Admin leaderboard'}).locator('tbody tr').count(),1);
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Export all dates CSV'}).click()]);
 assert.equal(download.suggestedFilename(),'fab-f1-leaderboard-all-dates.csv');
 await page.reload();await page.getByRole('button',{name:'Leaderboard',exact:true}).click();
 assert.equal(await page.getByRole('table',{name:'Admin leaderboard'}).locator('tbody tr').count(),1);
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByLabel('Target (seconds)').fill('5');await page.getByLabel('Headline').fill('FAB TIMING CHALLENGE');
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Draft saved'}).waitFor();
 await page.getByRole('button',{name:'Preview draft',exact:true}).click();
 const frame=page.frameLocator('iframe');await frame.getByRole('heading',{name:'FAB TIMING CHALLENGE'}).waitFor();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('fab-records')).length),1);
 await page.getByRole('button',{name:'Close preview'}).click();await page.getByLabel('Publication note').fill('Five-second test');await page.getByRole('button',{name:'Publish settings'}).click();
 await page.getByRole('status').filter({hasText:'Published on this browser'}).waitFor();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('fab-studio')).versions.at(-1).settings.target),5);
 await page.getByRole('button',{name:'Versions',exact:true}).click();await page.getByLabel('Restore change note').fill('Restore original for testing');await page.getByRole('button',{name:'Restore & publish selected version'}).last().click();
 await page.getByRole('status').filter({hasText:'Published on this browser'}).waitFor();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('fab-studio')).versions.at(-1).settings.target),10);
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('fab-records')).length),1);
 await page.getByRole('button',{name:'Page editor',exact:true}).click();
 await page.getByLabel('Page headline', {exact:true}).fill('LIVE EDITED FAB');
 await page.frameLocator('iframe').getByRole('heading',{name:'LIVE EDITED FAB'}).waitFor();
 assert.notEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('fab-studio')).versions.at(-1).settings.title),'LIVE EDITED FAB');
 await page.getByLabel('Subtitle ({target} supported)',{exact:true}).fill('AIM FOR {target} SECONDS');
 await page.frameLocator('iframe').getByText('AIM FOR 10.000 SECONDS',{exact:true}).waitFor();
 await page.getByLabel('Page', {exact:true}).selectOption('result');
 await page.getByLabel('Winning message',{exact:true}).fill('FAB PERFECT TIMING');
 await page.frameLocator('iframe').getByText('FAB PERFECT TIMING',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Draft saved'}).waitFor();
 await page.getByRole('button',{name:'Event branding',exact:true}).click();
 await page.getByLabel('Event name',{exact:true}).fill('FAB EVENT 2026');
 await page.getByLabel('primary colour',{exact:true}).fill('#123456');
 await page.frameLocator('iframe').getByText('FAB EVENT 2026',{exact:true}).waitFor();
 assert.equal(await page.frameLocator('iframe').locator('.game').evaluate(el=>getComputedStyle(el).getPropertyValue('--game-primary')),'#123456');
 await page.getByLabel('Change note',{exact:true}).fill('Live editor and branding test');
 await page.getByRole('button',{name:'Publish design',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Published on this browser'}).waitFor();
 await page.reload();await page.getByRole('button',{name:'Event branding',exact:true}).click();
 assert.equal(await page.getByLabel('Event name',{exact:true}).inputValue(),'FAB EVENT 2026');
 await page.getByRole('link',{name:'Back to game',exact:false}).click();
 await page.getByRole('heading',{name:'LIVE EDITED FAB'}).waitFor();
 await page.getByText('FAB EVENT 2026',{exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('fab-records')).length),1);
 await page.setViewportSize({width:390,height:844});await page.goto(url);assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 } finally {await browser.close();await new Promise(r=>server.close(r));}
});
